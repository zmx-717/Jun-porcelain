<script setup>
import { onMounted } from "vue";
import gsap from "gsap";
import ScrollTrigger from "gsap/ScrollTrigger";

// 注册 ScrollTrigger 插件
gsap.registerPlugin(ScrollTrigger);

onMounted(() => {
  // 为每个 .timeline-item 设置滑动动画
  gsap.utils.toArray(".timeline-item").forEach((item, index) => {
    gsap.fromTo(
      item,
      { y: 100, opacity: 0 }, // 初始状态：向下偏移 100px，透明度为 0
      {
        y: 0, // 最终状态：回到原位置
        opacity: 1, // 透明度为 1
        duration: 1.5, // 动画持续时间
        ease: "power3.out", // 使用缓动效果
        scrollTrigger: {
          trigger: item, // 触发动画的元素
          start: "top 80%", // 当 .timeline-item 进入视口 80% 时触发动画
          end: "top 30%", // 当 .timeline-item 离开视口 30% 时结束动画
          toggleActions: "play none none reverse", // 滚动时播放动画，反向滚动时反向播放
        },
      }
    );
  });

  // 为每个时间节点的小球设置动画
  gsap.utils.toArray(".timeline-dot").forEach((dot, index) => {
    gsap.fromTo(
      dot,
      { opacity: 1, y: -50 }, // 初始状态：透明度为 0，向上偏移 50px
      {
        opacity: 1, // 最终状态：透明度为 1
        y: 0, // 回到原位置
        duration: 1, // 动画持续时间
        ease: "power3.out", // 缓动效果
        scrollTrigger: {
          trigger: dot, // 触发动画的元素
          start: "top 85%", // 当小球进入视口 85% 时触发
          end: "top 40%", // 当小球离开视口 40% 时结束动画
          toggleActions: "play none none reverse", // 滚动时播放动画，反向滚动时反向播放
        },
      }
    );
  });

  // 为时间节点的文字设置动画
  gsap.utils.toArray(".timeline-time").forEach((time, index) => {
    gsap.fromTo(
      time,
      { x: -100, opacity: 0 }, // 初始状态：向左偏移 100px，透明度为 0
      {
        x: 0, // 最终状态：回到原位置
        opacity: 1, // 透明度为 1
        duration: 1, // 动画持续时间
        ease: "power3.out", // 缓动效果
        scrollTrigger: {
          trigger: time, // 触发动画的元素
          start: "top 90%", // 当时间节点进入视口 90% 时触发动画
          end: "top 50%", // 当时间节点离开视口 50% 时结束动画
          toggleActions: "play none none reverse", // 滚动时播放动画，反向滚动时反向播放
        },
      }
    );
  });

  const container = document.querySelector(".horizontal-scroll-container");
  const content = document.querySelector(".horizontal-scroll-content");
  const items = content.querySelectorAll(".horizontal-item");

  // 确保内容宽度足够触发滚动
  if (content.scrollWidth > container.offsetWidth) {
    const lastItemWidth = items[items.length - 1].offsetWidth; // 获取最后一个子元素的宽度
    const totalScrollDistance = content.scrollWidth - container.offsetWidth+100; // 总滚动距离
    const stopAtSecondLast = totalScrollDistance - 520; // 滚动到倒数第二个子元素的位置

    gsap.to(content, {
      x: () => -stopAtSecondLast, // 滚动到倒数第二个子元素
      ease: "power2.out",
      scrollTrigger: {
        trigger: container,
        pin: true,
        pinSpacing: true,
        scrub: 1,
        start: "top top", // 滚动开始时触发
        end: () => `+=${stopAtSecondLast}`, // 滚动停止在倒数第二个子元素
      },
    });
  }

  // 为每个横向滚动项设置入场动画
  gsap.utils.toArray(".horizontal-item").forEach((item) => {
    gsap.from(item, {
      opacity: 0,
      x: 100,
      duration: 1,
      scrollTrigger: {
        trigger: item,
        start: "top 85%", // 当元素进入视口 85% 时触发动画
        toggleActions: "play none none reverse",
      },
    });
  });



  gsap.utils.toArray(".img-item").forEach((img, index) => {
    gsap.fromTo(
      img,
      { y: 50, opacity: 0 }, // 初始状态：向下偏移 50px，透明度为 0
      {
        y: 0, // 最终状态：回到原位置
        opacity: 1, // 透明度为 1
        duration: 1.5, // 动画持续时间
        ease: "power3.out", // 缓动效果
        scrollTrigger: {
          trigger: img, // 触发动画的元素
          start: "top 80%", // 当图片进入视口 80% 时触发动画
          end: "top 50%", // 当图片离开视口 50% 时结束动画
          toggleActions: "play none none reverse", // 滚动时播放动画，反向滚动时反向播放
        },
      }
    );
  });
});
</script>
